import assert from "node:assert/strict";

export async function testSketchEditor(browser, url) {
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  try {
    await page.goto(url);
    await page.addScriptTag({ path: "tests/editor/rectangle.js" });
    await page.waitForFunction(()=>document.querySelector("#new-sketch")&&!document.querySelector("#new-sketch").disabled);
    const canvas=page.locator("#model-canvas");const bounds=await canvas.boundingBox();
    const cube={x:bounds.x+bounds.width-120,y:bounds.y,width:120,height:120};
    const originalView=await page.screenshot({clip:cube});
    await page.locator("#new-sketch").click();
    assert.equal(await page.locator("#workbench").inputValue(), "sketch");
    assert.deepEqual(await page.locator("#sketch-ribbon .tool-group > span").allTextContents(), ["Geometry", "Constraints", "Tools"]);
    assert.equal(await page.locator("#tool-panel [data-tool], #tool-panel [data-constraint]").count(), 0);
    assert.equal(await page.locator("#apply").isDisabled(),true);
    await page.evaluate(() => chooseSketchPlane("YZ"));
    await page.waitForFunction(()=>!document.querySelector("#apply").disabled);
    assert.ok(await page.locator("#tool-panel #sketch-construction").isVisible());
    assert.equal(await page.locator("#tool-panel #sketch-convert, #sketch-name, #sketch-hint").count(), 0);
    assert.equal(await page.locator("#sketch-ribbon #sketch-convert").count(), 0);
    assert.equal(await page.locator("#sketch-view").isVisible(),true);

    assert.equal(await page.locator('#sketch-ribbon [aria-pressed="true"]').count(), 0);
    assert.equal(await page.locator('#sketch-ribbon [data-tool="select"], #sketch-delete, #sketch-x, #sketch-y, #tool-panel #width, #tool-panel #height').count(), 0);
    const drawAt = (x, y) => [bounds.x + bounds.width / 2 + x * bounds.height / 60, bounds.y + bounds.height / 2 - y * bounds.height / 60];
    await page.locator('[data-tool="rectangle"]').click();
    await page.mouse.click(...drawAt(0, 0));
    await page.mouse.move(...drawAt(10, 6));
    await page.waitForFunction(() => document.querySelector("#progress").hidden);
    assert.ok(await page.locator('.sketch-live-dimensions #width').isVisible());
    await page.locator("#width").fill("20 / 2");await page.locator("#height").fill("6");
    await page.locator("#width").press("Tab");assert.equal(await page.locator("#height").evaluate(n=>n===document.activeElement),true);
    await page.locator("#height").press("Shift+Tab");assert.equal(await page.locator("#width").evaluate(n=>n===document.activeElement),true);
    await page.waitForFunction(() => document.querySelector("#progress").hidden);
    await page.screenshot({path:"/private/tmp/pamatcad-sketch-live-dimensions.png"});
    await page.locator("#width").press("Enter");
    await page.waitForFunction(()=>!document.querySelector("#progress").hidden===false&&document.querySelector("#status").textContent.includes("added"));
    assert.equal(await page.locator('[data-tool="rectangle"]').getAttribute("aria-pressed"), "true");
    assert.equal(await page.locator('.sketch-live-dimensions').isVisible(), false);
    await page.locator('[data-tool="circle"]').click();
    await page.mouse.click(...drawAt(-16, 0));
    await page.mouse.move(...drawAt(-13, 0));
    await page.locator("#sketch-radius").fill("3");
    await page.locator("#sketch-radius").press("Enter");
    await page.waitForFunction(()=>document.querySelector("#status").textContent==="Circle added"&&!document.querySelector("#apply").disabled);
    assert.equal(await page.locator('[data-tool="circle"]').getAttribute("aria-pressed"), "true");
    await page.locator('[data-tool="rectangle"]').click();
    await page.mouse.click(...drawAt(-15, -10));
    await page.mouse.move(...drawAt(-10, -5));
    await page.keyboard.press("Escape");
    await page.waitForFunction(() => document.querySelector("#progress").hidden);
    assert.equal(await page.locator('#sketch-ribbon [aria-pressed="true"]').count(), 0);
    assert.ok(await page.locator("#sketch-workspace").isVisible(), "Escape leaves the sketch open");
    await page.locator('[data-tool="line"]').click();
    await page.locator('[data-tool="line"]').click();
    assert.equal(await page.locator('#sketch-ribbon [aria-pressed="true"]').count(), 0, "The active tool toggles off");
    const documentId = await page.locator('#document-tabs [aria-selected="true"]').getAttribute("data-document");
    await page.getByText("File", {exact:true}).click(); await page.locator("#menu-new").click();
    await page.waitForFunction(id => document.querySelector('#document-tabs [aria-selected="true"]').getAttribute("data-document") !== id && !document.querySelector("#workbench").disabled, documentId);
    assert.equal(await page.locator("#workbench").inputValue(), "solid");
    await page.locator(`#document-tabs [data-document="${documentId}"]`).click();
    assert.equal(await page.locator("#workbench").inputValue(), "sketch");
    assert.equal(await page.locator('#sketch-ribbon [aria-pressed="true"]').count(), 0);
    await page.locator("#workbench").selectOption("solid");
    assert.ok(await page.locator("#new-sketch").isDisabled());
    await page.locator("#workbench").selectOption("sketch");
    assert.ok(await page.locator("#sketch-workspace").isVisible());
    const icons = await page.locator("#sketch-ribbon button").evaluateAll(buttons => buttons.length > 20 && buttons.every(button => button.querySelector("svg [class]")));
    assert.ok(icons, "Every geometry, constraint, and tool icon loads");
    await page.setViewportSize({width:960,height:840});
    assert.ok(await page.locator(".ribbon").evaluate(ribbon => ribbon.getBoundingClientRect().right <= innerWidth));
    assert.ok(await page.locator("#sketch-ribbon .tools").evaluateAll(groups => groups.every(group => getComputedStyle(group).gridTemplateRows.split(" ").length === 2)));
    await page.screenshot({path:"/private/tmp/pamatcad-sketch-ribbon.png"});
    await page.setViewportSize({width:1440,height:1000});
    const lines=page.getByRole("button",{name:"Show lines",exact:true});await lines.click();await lines.click();
    await page.screenshot({path:"/private/tmp/pamatcad-sketch-workspace.png"});
    await page.locator("#apply").click();
    await page.waitForFunction(()=>document.querySelector("#features").children.length===1&&!document.querySelector("#new-sketch").disabled);
    assert.equal(await page.locator("#workbench").inputValue(), "solid");
    assert.ok((await page.screenshot({clip:cube})).equals(originalView),"Finish restores pre-sketch orientation");
    await page.locator("#toggle-output").click();
    const evaluate=async source=>{
      await page.locator("#js").fill(source);await page.locator("#js").press("Enter");
      await page.waitForFunction(()=>!document.querySelector("#js").disabled);
      return JSON.parse(await page.locator("#console-output > :last-child").textContent());
    };
    const state=await evaluate('return await (await scene.sketches.get((await scene.timeline.list())[0].id)).state()');
    assert.equal(state.sketch.plane.plane,"yz");assert.equal(state.entities.filter(e=>e.geometry.type==="line").length,4);
    assert.equal(state.entities.filter(e=>e.geometry.type==="circle").length,1);assert.equal(state.dimensions.length,3);
    assert.ok(state.dimensions.some(d=>d.parameters.value==="20 / 2"));
    const volume=await evaluate('const s=await scene.sketches.get((await scene.timeline.list())[0].id); const f=await core.solid.extrude(await s.regions.all(),{length1:2}); return (await Promise.all(f.newSolids.map(async b=>(await (await scene.bodies.get(b.id)).properties()).volume.value))).reduce((a,b)=>a+b,0)');
    assert.ok(Math.abs(volume-(60+Math.PI*9)*2)<1e-7);
    await page.locator("#features li").first().dblclick();
    await page.waitForFunction(()=>document.querySelector("#sketch-workspace")&&!document.querySelector("#apply").disabled);
    assert.ok(await page.locator("#sketch-workspace").isVisible());
    const editView = await canvas.boundingBox();
    await page.mouse.click(editView.x + editView.width / 2 + 6 * editView.height / 60, editView.y + editView.height / 2);
    await page.waitForFunction(() => document.querySelector("#sketch-status").textContent.startsWith("Line"));
    await page.locator("#cancel").click();await page.waitForFunction(()=>!document.querySelector("#new-sketch").disabled);
    assert.equal(await page.locator("#workbench").inputValue(), "solid");
    assert.equal(await page.locator("#features li").count(),2);
    await page.getByText("File", {exact:true}).click(); await page.locator("#menu-new").click();
    await page.waitForFunction(() => !document.querySelector("#js").disabled && !document.querySelector("#features").children.length);
    await evaluate('const s=await scene.sketches.create(scene.construction.builtin.planes.xy); await s.primitives.add("line",{from:[0,0],to:[20,0]}); await s.complete(); return {id:s.id}');
    await page.locator("#features li").first().dblclick();
    await page.waitForFunction(() => document.querySelector("#sketch-workspace") && !document.querySelector("#apply").disabled);
    const view = await canvas.boundingBox();
    const at = (x, y) => page.mouse.click(view.x + view.width / 2 + x * view.height / 60, view.y + view.height / 2 - y * view.height / 60);
    await at(10, 0);
    await page.waitForFunction(() => document.querySelector("#sketch-status").textContent.startsWith("Line"));
    await page.locator('#sketch-ribbon [data-constraint="horizontal"]').click();
    await page.waitForFunction(() => document.querySelector("#progress").hidden && document.querySelector("#sketch-status").textContent.includes("3 sketch DOF"));
    await page.keyboard.press("Escape");
    await at(9, 0); // The H label is drawn over the line and must win the pick.
    await page.keyboard.press("Delete");
    await page.waitForFunction(() => document.querySelector("#progress").hidden && document.querySelector("#sketch-status").textContent.includes("4 sketch DOF"));
    await page.locator("#apply").click();
    await page.waitForFunction(() => !document.querySelector("#js").disabled);
    const edited = await evaluate('return await (await scene.sketches.get((await scene.timeline.list())[0].id)).state()');
    assert.equal(edited.entities.filter(e => e.geometry.type === "line").length, 1, "Deleting the constraint preserves the line underneath");
    assert.ok(!edited.constraints.some(c => c.kind === "horizontal"));
    assert.equal(edited.status.degreesOfFreedom, 4);
    await evaluate('const s=await scene.sketches.get((await scene.timeline.list())[0].id); await s.edit(); const line=(await s.state()).entities.find(e=>e.geometry.type==="line"); await s.dimensions.add("length",{line:line.reference,mode:"driven"}); await s.complete(); return {added:true}');
    await page.locator("#features li").first().dblclick();
    await page.waitForFunction(() => document.querySelector("#sketch-workspace") && !document.querySelector("#apply").disabled);
    await at(10, 1.5);
    await page.keyboard.press("Delete");
    await page.waitForFunction(() => document.querySelector("#progress").hidden);
    await page.locator("#apply").click();
    await page.waitForFunction(() => !document.querySelector("#js").disabled);
    const undimensioned = await evaluate('return await (await scene.sketches.get((await scene.timeline.list())[0].id)).state()');
    assert.equal(undimensioned.dimensions.length, 0, "Delete removes a selected dimension");
    assert.equal(undimensioned.entities.filter(e => e.geometry.type === "line").length, 1, "Dimension deletion preserves geometry");
    await page.locator("#features li").first().dblclick();
    await page.waitForFunction(() => document.querySelector("#sketch-workspace") && !document.querySelector("#apply").disabled);
    await at(10, 0);
    await page.locator('#sketch-ribbon [data-tool="text"]').click();
    await page.locator("#sketch-text").fill("keep me");
    await page.locator("#sketch-text").press("Backspace");
    assert.equal(await page.locator("#sketch-text").inputValue(), "keep m", "Backspace edits an input without deleting geometry");
    await page.keyboard.press("Escape");
    await canvas.focus();
    await page.waitForFunction(() => document.querySelector("#progress").hidden);
    await at(10, 0);
    await page.keyboard.press("Backspace");
    await page.waitForFunction(() => document.querySelector("#progress").hidden);
    await page.locator("#apply").click();
    await page.waitForFunction(() => !document.querySelector("#js").disabled);
    const removed = await evaluate('return await (await scene.sketches.get((await scene.timeline.list())[0].id)).state()');
    assert.equal(removed.entities.filter(e => e.geometry.type === "line").length, 0, "Backspace removes selected geometry");
    assert.deepEqual(errors,[]);
    console.log("Sketch workspace: ribbon groups, icons, workbench/tab restoration, construction controls, formulas, camera restoration, edit/cancel and extrusion passed");
  }finally{await context.close();}
}
