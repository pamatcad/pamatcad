#[repr(C)]
struct CellGroup {
    targets: *const usize,
    target_count: usize,
    tools: *const usize,
    tool_count: usize,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub(crate) struct PrismSide<'a> {
    target: *const c_void,
    length: f64,
    taper: f64,
    extent: i32,
    borrow: std::marker::PhantomData<&'a Shape>,
}
impl<'a> PrismSide<'a> {
    pub fn new(target: Option<&'a Shape>, length: f64, taper: f64, extent: i32) -> Self {
        Self {
            target: target.map_or(std::ptr::null(), |s| s.raw.as_ptr()),
            length,
            taper: taper.to_radians(),
            extent,
            borrow: std::marker::PhantomData,
        }
    }
}
#[repr(C)]
pub(crate) struct PrismOptions<'a> {
    pub normal: [f64; 3],
    pub origin: [f64; 3],
    pub offset: f64,
    pub sides: [PrismSide<'a>; 2],
    pub two_sides: i32,
}
extern "C" {
    fn pamat_partition(
        targets: *const *const c_void,
        target_count: usize,
        tools: *const *const c_void,
        tool_count: usize,
        join: i32,
        output: *mut *mut c_void,
        count: *mut usize,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_partition_group(partition: *const c_void, index: usize) -> CellGroup;
    fn pamat_partition_result(
        partition: *mut c_void,
        group: usize,
        survivor: usize,
        output: *mut *mut c_void,
        changed: *mut i32,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_partition_free(partition: *mut c_void);

    fn pamat_extrude(
        points: *const f64,
        count: usize,
        options: *const PrismOptions,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_extrude_circle(
        center: *const f64,
        radius: f64,
        options: *const PrismOptions,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_extrude_face(
        body: *const c_void,
        face_id: usize,
        options: *const PrismOptions,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_axial_bounds(
        body: *const c_void,
        slot: usize,
        origin: *const f64,
        normal: *const f64,
        bounds: *mut f64,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_face_properties(
        body: *const c_void,
        slot: usize,
        props: *mut f64,
        surface: *mut i32,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_face_count(shape: *const c_void, face_id: usize) -> usize;
    fn pamat_face_slots(shape: *const c_void) -> usize;
    fn pamat_face_ids(
        shape: *const c_void,
        first: usize,
        count: usize,
        sink: extern "C" fn(*mut c_void, usize),
        context: *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_face_by_normal(
        shape: *const c_void,
        normal: *const f64,
        count: *mut usize,
        face_id: *mut usize,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_face_frame(
        shape: *const c_void,
        face_id: usize,
        frame: *mut f64,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_write_step(
        shapes: *const *const c_void,
        count: usize,
        sink: extern "C" fn(*mut c_void, *const u8, usize),
        context: *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_proxy(
        shape: *const c_void,
        face_sink: extern "C" fn(
            *mut c_void,
            usize,
            usize,
            *const f32,
            *const f32,
            usize,
            *const u32,
        ),
        edge_sink: extern "C" fn(*mut c_void, usize, usize, *const f32, i32),
        context: *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_mesh(
        shape: *const c_void,
        sink: extern "C" fn(*mut c_void, *const f64),
        context: *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_volume(
        shape: *const c_void,
        output: *mut f64,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_shape_free(shape: *mut c_void);
}

// A shape stays on its engine's thread and has exactly one Rust owner.
pub struct Shape {
    raw: NonNull<c_void>,
    // Slots generated by the current command, keyed by input profile index.
    // Commit moves these into the feature's record before publishing the body.
    pub(crate) profile_slots: Vec<(usize, Range<usize>)>,
}

fn failure(error: &[c_char]) -> CoreError {
    let message = unsafe { CStr::from_ptr(error.as_ptr()) }
        .to_string_lossy()
        .into_owned();
    CoreError::new(ErrorCode::KernelFailure, message)
}

fn extrusion_failure(status: i32, error: &[c_char]) -> CoreError {
    let mut result = failure(error);
    if status == 2 {
        result.code = ErrorCode::InvalidParameter;
    }
    result
}

impl Shape {
    fn from_raw(raw: NonNull<c_void>) -> Self {
        Self {
            raw,
            profile_slots: Vec::new(),
        }
    }

    pub(crate) fn record_profile(&mut self, index: usize) {
        let slots = self.slot_count();
        self.profile_slots.push((index, 0..slots));
    }

    pub(crate) fn extrude(points: &[[f64; 3]], options: &PrismOptions) -> Result<Self> {
        let mut output = std::ptr::null_mut();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_extrude(
                points.as_ptr().cast(),
                points.len(),
                options,
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(extrusion_failure(status, &error));
        }
        NonNull::new(output).map(Self::from_raw).ok_or_else(|| {
            CoreError::new(
                ErrorCode::KernelFailure,
                "OCCT returned an empty shape handle",
            )
        })
    }

    pub(crate) fn extrude_circle(
        center: [f64; 3],
        radius: f64,
        options: &PrismOptions,
    ) -> Result<Self> {
        let mut output = std::ptr::null_mut();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_extrude_circle(
                center.as_ptr(),
                radius,
                options,
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(extrusion_failure(status, &error));
        }
        NonNull::new(output).map(Self::from_raw).ok_or_else(|| {
            CoreError::new(
                ErrorCode::KernelFailure,
                "OCCT returned an empty shape handle",
            )
        })
    }

    pub(crate) fn extrude_face(&self, face_id: usize, options: &PrismOptions) -> Result<Self> {
        let mut output = std::ptr::null_mut();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_extrude_face(
                self.raw.as_ptr(),
                face_id,
                options,
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(extrusion_failure(status, &error));
        }
        NonNull::new(output).map(Self::from_raw).ok_or_else(|| {
            CoreError::new(
                ErrorCode::KernelFailure,
                "OCCT returned an empty shape handle",
            )
        })
    }

    pub(crate) fn axial_bounds(&self, slot: Option<usize>, frame: Frame) -> Result<[f64; 2]> {
        if let Some(id) = slot {
            Self::require_one_face(unsafe { pamat_face_count(self.raw.as_ptr(), id) })?;
        }
        let mut error = [0; 1024];
        let mut bounds = [0.; 2];
        let status = unsafe {
            pamat_axial_bounds(
                self.raw.as_ptr(),
                slot.unwrap_or(usize::MAX),
                frame.origin.as_ptr(),
                frame.normal.as_ptr(),
                bounds.as_mut_ptr(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(bounds)
    }

    pub(crate) fn face_properties(&self, id: usize) -> Result<FaceProperties> {
        Self::require_one_face(unsafe { pamat_face_count(self.raw.as_ptr(), id) })?;
        let mut error = [0; 1024];
        let mut values = [0.; 4];
        let mut surface = 0;
        let status = unsafe {
            pamat_face_properties(
                self.raw.as_ptr(),
                id,
                values.as_mut_ptr(),
                &mut surface,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        let [area_mm2, x, y, z] = values;
        Ok(FaceProperties {
            area_mm2,
            centroid: [x, y, z],
            frame: if surface == 1 {
                Some(self.face_frame(id)?)
            } else {
                None
            },
            surface: match surface {
                1 => SurfaceType::Plane,
                2 => SurfaceType::Cylinder,
                3 => SurfaceType::Cone,
                _ => SurfaceType::Other,
            },
        })
    }

    pub(crate) fn slot_count(&self) -> usize {
        unsafe { pamat_face_slots(self.raw.as_ptr()) }
    }

    pub fn face_ids(&self, slots: Option<Range<usize>>) -> Result<Vec<usize>> {
        extern "C" fn append(context: *mut c_void, id: usize) {
            // The caller owns this vector for the duration of the synchronous traversal.
            unsafe { (*context.cast::<Vec<usize>>()).push(id) }
        }
        let (first, count) = slots.map_or((0, usize::MAX), |r| (r.start, r.len()));
        let mut ids = Vec::new();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_face_ids(
                self.raw.as_ptr(),
                first,
                count,
                append,
                (&mut ids as *mut Vec<usize>).cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(ids)
    }

    pub fn face_by_normal(&self, direction: [f64; 3]) -> Result<usize> {
        let norm = direction[0].hypot(direction[1]).hypot(direction[2]);
        if !norm.is_finite() || norm == 0. {
            return Err(CoreError::new(
                ErrorCode::InvalidParameter,
                "Face normal must be finite and nonzero",
            ));
        }
        let normal = direction.map(|x| x / norm);
        let mut count = 0;
        let mut id = 0;
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_face_by_normal(
                self.raw.as_ptr(),
                normal.as_ptr(),
                &mut count,
                &mut id,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Self::require_one_face(count)?;
        Ok(id)
    }

    fn require_one_face(count: usize) -> Result<()> {
        match count {
            1 => Ok(()),
            0 => Err(CoreError::new(ErrorCode::NotFound, "No matching face")),
            _ => Err(CoreError::new(
                ErrorCode::AmbiguousFace,
                "Multiple matching faces",
            )),
        }
    }

    pub fn face_frame(&self, id: usize) -> Result<Frame> {
        Self::require_one_face(unsafe { pamat_face_count(self.raw.as_ptr(), id) })?;
        let mut coords = [[0.; 3]; 4];
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_face_frame(
                self.raw.as_ptr(),
                id,
                coords.as_mut_ptr().cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        let [origin, u, v, normal] = coords;
        Ok(Frame {
            origin,
            u,
            v,
            normal,
        })
    }

    pub fn write_step(shapes: &[&Shape]) -> Result<Vec<u8>> {
        extern "C" fn append(context: *mut c_void, data: *const u8, len: usize) {
            // Both pointers are valid for this synchronous call; the writer owns the byte slice.
            unsafe {
                (*context.cast::<Vec<u8>>())
                    .extend_from_slice(std::slice::from_raw_parts(data, len))
            }
        }
        let handles: Vec<_> = shapes.iter().map(|s| s.raw.as_ptr().cast_const()).collect();
        let mut bytes = Vec::new();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_write_step(
                handles.as_ptr(),
                handles.len(),
                append,
                (&mut bytes as *mut Vec<u8>).cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(bytes)
    }

    pub fn proxy(&self, body: BodyRef, revision: String) -> Result<BodyProxy> {
        extern "C" fn face(
            ctx: *mut c_void,
            id: usize,
            nodes: usize,
            xyz: *const f32,
            normals: *const f32,
            triangles: usize,
            indices: *const u32,
        ) {
            // Each slice lives for this callback and is copied into the owned proxy.
            unsafe {
                let p = &mut *ctx.cast::<BodyProxy>();
                let base = (p.positions.len() / 3) as u32;
                p.faces.push(ProxyFace {
                    face: FaceRef::Selected {
                        scene_id: p.body.scene_id.clone(),
                        body_id: p.body.id.clone(),
                        face_id: id,
                    },
                    first_triangle: p.triangles.len() / 3,
                    triangle_count: triangles,
                });
                p.positions
                    .extend_from_slice(std::slice::from_raw_parts(xyz, nodes * 3));
                p.normals
                    .extend_from_slice(std::slice::from_raw_parts(normals, nodes * 3));
                p.triangles.extend(
                    std::slice::from_raw_parts(indices, triangles * 3)
                        .iter()
                        .map(|i| base + i),
                );
            }
        }
        extern "C" fn edge(
            ctx: *mut c_void,
            id: usize,
            count: usize,
            xyz: *const f32,
            closed: i32,
        ) {
            unsafe {
                let p = &mut *ctx.cast::<BodyProxy>();
                p.edges.push(ProxyEdge {
                    edge: EdgeRef {
                        scene_id: p.body.scene_id.clone(),
                        body_id: p.body.id.clone(),
                        edge_id: id,
                        revision: p.revision.clone(),
                    },
                    first_point: p.edge_points.len() / 3,
                    point_count: count,
                    closed: closed != 0,
                });
                p.edge_points
                    .extend_from_slice(std::slice::from_raw_parts(xyz, count * 3));
            }
        }
        let mut p = BodyProxy {
            body,
            revision,
            positions: vec![],
            normals: vec![],
            triangles: vec![],
            faces: vec![],
            edge_points: vec![],
            edges: vec![],
        };
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_proxy(
                self.raw.as_ptr(),
                face,
                edge,
                (&mut p as *mut BodyProxy).cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(p)
    }

    pub fn triangle_mesh(&self) -> Result<crate::protocol::TriangleMesh> {
        let mut triangles = Vec::new();
        self.mesh(&mut triangles)?;
        Ok(crate::protocol::TriangleMesh { triangles })
    }

    pub fn mesh(&self, triangles: &mut Vec<[[f64; 3]; 3]>) -> Result<()> {
        extern "C" fn append(context: *mut c_void, xyz: *const f64) {
            // The mesher supplies nine consecutive world-space coordinates per triangle.
            unsafe { (*context.cast::<Vec<[[f64; 3]; 3]>>()).push(*xyz.cast::<[[f64; 3]; 3]>()) }
        }
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_mesh(
                self.raw.as_ptr(),
                append,
                (triangles as *mut Vec<[[f64; 3]; 3]>).cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(())
    }

    pub fn volume(&self) -> Result<f64> {
        let mut output = 0.0;
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_volume(
                self.raw.as_ptr(),
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(output)
    }
}

impl Drop for Shape {
    fn drop(&mut self) {
        unsafe { pamat_shape_free(self.raw.as_ptr()) }
    }
}

// The partition borrows its input shapes. Each materialized result has its own owner.
pub(crate) struct CellPartition<'a> {
    raw: NonNull<c_void>,
    pub group_count: usize,
    inputs: std::marker::PhantomData<&'a Shape>,
}

impl<'a> CellPartition<'a> {
    pub fn new(targets: &[&'a Shape], tools: &'a [Shape], join: bool) -> Result<Self> {
        let handles = |s: &Shape| s.raw.as_ptr().cast_const();
        let bodies: Vec<_> = targets.iter().map(|s| handles(s)).collect();
        let tools: Vec<_> = tools.iter().map(handles).collect();
        let mut raw = std::ptr::null_mut();
        let mut group_count = 0;
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_partition(
                bodies.as_ptr(),
                bodies.len(),
                tools.as_ptr(),
                tools.len(),
                join.into(),
                &mut raw,
                &mut group_count,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(Self {
            raw: NonNull::new(raw).expect("successful partition"),
            group_count,
            inputs: std::marker::PhantomData,
        })
    }

    pub fn members(&self, group: usize) -> (&[usize], &[usize]) {
        assert!(group < self.group_count);
        let info = unsafe { pamat_partition_group(self.raw.as_ptr(), group) };
        // Empty C++ vectors may have a null data pointer; both lists live with self.
        let targets = if info.target_count == 0 {
            &[]
        } else {
            unsafe { std::slice::from_raw_parts(info.targets, info.target_count) }
        };
        let tools = unsafe { std::slice::from_raw_parts(info.tools, info.tool_count) };
        (targets, tools)
    }

    pub fn result(&mut self, group: usize, survivor: usize) -> Result<(Option<Shape>, bool)> {
        assert!(group < self.group_count);
        let mut raw = std::ptr::null_mut();
        let mut changed = 0;
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_partition_result(
                self.raw.as_ptr(),
                group,
                survivor,
                &mut raw,
                &mut changed,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok((NonNull::new(raw).map(Shape::from_raw), changed != 0))
    }
}

impl Drop for CellPartition<'_> {
    fn drop(&mut self) {
        unsafe { pamat_partition_free(self.raw.as_ptr()) }
    }
}
