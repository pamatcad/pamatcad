use crate::error::{CoreError, ErrorCode, Result};
use crate::sketch::Frame;
use std::{
    ffi::{c_char, c_void, CStr},
    ops::Range,
    ptr::NonNull,
};

extern "C" {
    fn pamat_extrude(
        points: *const f64,
        count: usize,
        direction: *const f64,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_extrude_circle(
        center: *const f64,
        radius: f64,
        normal: *const f64,
        direction: *const f64,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_cut(
        body: *const c_void,
        tool: *const c_void,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_join(
        body: *const c_void,
        tool: *const c_void,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_extrude_face(
        body: *const c_void,
        face_id: usize,
        direction: *const f64,
        output: *mut *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_face_count(shape: *const c_void, face_id: usize) -> usize;
    fn pamat_face_slots(shape: *const c_void) -> usize;
    fn pamat_face_ids(
        shape: *mut c_void,
        first: usize,
        count: usize,
        sink: extern "C" fn(*mut c_void, usize),
        context: *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_face_by_normal(
        shape: *mut c_void,
        normal: *const f64,
        count: *mut usize,
        face_id: *mut usize,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_face_frame(
        shape: *const c_void,
        face_id: usize,
        frame: *mut f64,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_write_step(
        shapes: *const *const c_void,
        count: usize,
        sink: extern "C" fn(*mut c_void, *const u8, usize),
        context: *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_mesh(
        shape: *const c_void,
        sink: extern "C" fn(*mut c_void, *const f64),
        context: *mut c_void,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_volume(
        shape: *const c_void,
        output: *mut f64,
        error: *mut c_char,
        error_size: usize,
    ) -> i32;
    fn pamat_shape_free(shape: *mut c_void);
}

// A shape stays on its engine's thread and has exactly one Rust owner.
pub struct Shape {
    raw: NonNull<c_void>,
    // Slots generated by the current command, keyed by input profile index.
    // Commit moves these into the feature's record before publishing the body.
    pub(crate) profile_slots: Vec<(usize, Range<usize>)>,
}

fn failure(error: &[c_char]) -> CoreError {
    let message = unsafe { CStr::from_ptr(error.as_ptr()) }
        .to_string_lossy()
        .into_owned();
    CoreError::new(ErrorCode::KernelFailure, message)
}

impl Shape {
    fn from_raw(raw: NonNull<c_void>) -> Self {
        Self {
            raw,
            profile_slots: Vec::new(),
        }
    }

    pub(crate) fn record_profile(&mut self, index: usize) {
        let slots = unsafe { pamat_face_slots(self.raw.as_ptr()) };
        self.profile_slots.push((index, 0..slots));
    }

    pub fn extrude(points: &[[f64; 3]], direction: [f64; 3]) -> Result<Self> {
        let mut output = std::ptr::null_mut();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_extrude(
                points.as_ptr().cast(),
                points.len(),
                direction.as_ptr(),
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        NonNull::new(output).map(Self::from_raw).ok_or_else(|| {
            CoreError::new(
                ErrorCode::KernelFailure,
                "OCCT returned an empty shape handle",
            )
        })
    }

    pub fn extrude_circle(
        center: [f64; 3],
        radius: f64,
        normal: [f64; 3],
        direction: [f64; 3],
    ) -> Result<Self> {
        let mut output = std::ptr::null_mut();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_extrude_circle(
                center.as_ptr(),
                radius,
                normal.as_ptr(),
                direction.as_ptr(),
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        NonNull::new(output).map(Self::from_raw).ok_or_else(|| {
            CoreError::new(
                ErrorCode::KernelFailure,
                "OCCT returned an empty shape handle",
            )
        })
    }

    pub fn extrude_face(&self, face_id: usize, direction: [f64; 3]) -> Result<Self> {
        let mut output = std::ptr::null_mut();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_extrude_face(
                self.raw.as_ptr(),
                face_id,
                direction.as_ptr(),
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        NonNull::new(output).map(Self::from_raw).ok_or_else(|| {
            CoreError::new(
                ErrorCode::KernelFailure,
                "OCCT returned an empty shape handle",
            )
        })
    }

    pub fn cut(&self, tool: &Shape) -> Result<Option<Self>> {
        self.apply_boolean(tool, pamat_cut)
    }

    pub fn join(&self, tool: &Shape) -> Result<Option<Self>> {
        self.apply_boolean(tool, pamat_join)
    }

    fn apply_boolean(
        &self,
        tool: &Shape,
        operation: unsafe extern "C" fn(
            *const c_void,
            *const c_void,
            *mut *mut c_void,
            *mut c_char,
            usize,
        ) -> i32,
    ) -> Result<Option<Self>> {
        let mut output = std::ptr::null_mut();
        let mut error = [0; 1024];
        let status = unsafe {
            operation(
                self.raw.as_ptr(),
                tool.raw.as_ptr(),
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(NonNull::new(output).map(|raw| {
            let offset = unsafe { pamat_face_slots(self.raw.as_ptr()) };
            let mut profile_slots = self.profile_slots.clone();
            profile_slots.extend(
                tool.profile_slots
                    .iter()
                    .map(|(i, range)| (*i, offset + range.start..offset + range.end)),
            );
            Self { raw, profile_slots }
        }))
    }

    pub fn face_ids(&self, slots: Option<Range<usize>>) -> Result<Vec<usize>> {
        extern "C" fn append(context: *mut c_void, id: usize) {
            // The caller owns this vector for the duration of the synchronous traversal.
            unsafe { (*context.cast::<Vec<usize>>()).push(id) }
        }
        let (first, count) = slots.map_or((0, usize::MAX), |r| (r.start, r.len()));
        let mut ids = Vec::new();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_face_ids(
                self.raw.as_ptr(),
                first,
                count,
                append,
                (&mut ids as *mut Vec<usize>).cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(ids)
    }

    pub fn face_by_normal(&self, direction: [f64; 3]) -> Result<usize> {
        let norm = direction[0].hypot(direction[1]).hypot(direction[2]);
        if !norm.is_finite() || norm == 0. {
            return Err(CoreError::new(
                ErrorCode::InvalidParameter,
                "Face normal must be finite and nonzero",
            ));
        }
        let normal = direction.map(|x| x / norm);
        let mut count = 0;
        let mut id = 0;
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_face_by_normal(
                self.raw.as_ptr(),
                normal.as_ptr(),
                &mut count,
                &mut id,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Self::require_one_face(count)?;
        Ok(id)
    }

    fn require_one_face(count: usize) -> Result<()> {
        match count {
            1 => Ok(()),
            0 => Err(CoreError::new(ErrorCode::NotFound, "No matching face")),
            _ => Err(CoreError::new(
                ErrorCode::AmbiguousFace,
                "Multiple matching faces",
            )),
        }
    }

    pub fn face_frame(&self, id: usize) -> Result<Frame> {
        Self::require_one_face(unsafe { pamat_face_count(self.raw.as_ptr(), id) })?;
        let mut coords = [[0.; 3]; 4];
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_face_frame(
                self.raw.as_ptr(),
                id,
                coords.as_mut_ptr().cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        let [origin, u, v, normal] = coords;
        Ok(Frame {
            origin,
            u,
            v,
            normal,
        })
    }

    pub fn write_step(shapes: &[&Shape]) -> Result<Vec<u8>> {
        extern "C" fn append(context: *mut c_void, data: *const u8, len: usize) {
            // Both pointers are valid for this synchronous call; the writer owns the byte slice.
            unsafe {
                (*context.cast::<Vec<u8>>())
                    .extend_from_slice(std::slice::from_raw_parts(data, len))
            }
        }
        let handles: Vec<_> = shapes.iter().map(|s| s.raw.as_ptr().cast_const()).collect();
        let mut bytes = Vec::new();
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_write_step(
                handles.as_ptr(),
                handles.len(),
                append,
                (&mut bytes as *mut Vec<u8>).cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(bytes)
    }

    pub fn mesh(&self, triangles: &mut Vec<[[f64; 3]; 3]>) -> Result<()> {
        extern "C" fn append(context: *mut c_void, xyz: *const f64) {
            // The mesher supplies nine consecutive world-space coordinates per triangle.
            unsafe { (*context.cast::<Vec<[[f64; 3]; 3]>>()).push(*xyz.cast::<[[f64; 3]; 3]>()) }
        }
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_mesh(
                self.raw.as_ptr(),
                append,
                (triangles as *mut Vec<[[f64; 3]; 3]>).cast(),
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(())
    }

    pub fn volume(&self) -> Result<f64> {
        let mut output = 0.0;
        let mut error = [0; 1024];
        let status = unsafe {
            pamat_volume(
                self.raw.as_ptr(),
                &mut output,
                error.as_mut_ptr(),
                error.len(),
            )
        };
        if status != 0 {
            return Err(failure(&error));
        }
        Ok(output)
    }
}

impl Drop for Shape {
    fn drop(&mut self) {
        unsafe { pamat_shape_free(self.raw.as_ptr()) }
    }
}
